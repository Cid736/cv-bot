def svg(name: str, size: int = 18) -> str:
    return (f'<svg class="icon" width="{size}" height="{size}" viewBox="0 0 24 24" fill="none" '
            f'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" '
            f'aria-hidden="true" focusable="false">{ICONS[name]}</svg>')


def icon(name: str, size: int = 18) -> Markup:
    return Markup(svg(name, size))


def icons_json() -> Markup:
    # Embedded in <script type="application/json">: escape "</" so it can't close the tag.
    return Markup(json.dumps(ICONS).replace("</", "<\\/"))
